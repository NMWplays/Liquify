export const LANGUAGE_KEY = "liquify-language";

const LANGUAGE_NAMES: Record<string, string> = {
  en: "English",
  de: "Deutsch",
  ru: "Русский",
  es: "Español",
  pt: "Português",
  tr: "Türkçe",
  hi: "हिन्दी",
  sv: "Svenska",
  ja: "日本語",
  zh: "中文",
  ko: "한국어",
};

export function getAvailableLanguages(): Array<{ value: string; label: string }> {
  return Object.keys(liquifyTranslations).map((code) => ({
    value: code,
    label: LANGUAGE_NAMES[code] || code,
  }));
}

function getSpotifyLanguage(): string {
  const raw = (
    (window as any).SpotiKit?.Locale?.language ||
    navigator.language ||
    "en"
  ).toString().toLowerCase();
  const base = raw.split(/[-_]/)[0];
  if (raw.startsWith("zh")) return "zh";
  if (raw.startsWith("pt")) return "pt";
  return base;
}

export function getLanguageMode(): string {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  if (!saved || saved === "auto") return "auto";
  return liquifyTranslations[saved] ? saved : "auto";
}

function getClientLanguage(): string {
  const mode = getLanguageMode();
  return mode === "auto" ? getSpotifyLanguage() : mode;
}

export function getEffectiveLanguage(): string {
  const lang = getClientLanguage();
  return liquifyTranslations[lang] ? lang : "en";
}

export function setLanguage(mode: string): void {
  localStorage.setItem(LANGUAGE_KEY, mode);
  window.dispatchEvent(new Event("liquifyLanguageChanged"));
}

export function getTranslation() {
  const lang = getClientLanguage();
  return deepMerge(settingsCopy, liquifyTranslations[lang] || liquifyTranslations.en);
}
